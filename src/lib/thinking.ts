/**
 * Фразы индикатора «копилот думает».
 *
 * Ожидание у копилота живое: он ходит в модель, а та в свою очередь может
 * думать десяток секунд. Одна застывшая надпись за это время начинает
 * читаться как подвисший интерфейс, поэтому фраза меняется.
 */

/** Первая фраза всегда одна: сначала надо подтвердить, что запрос принят. */
export const FIRST_PHRASE = "Думаю...";

/** Дальше — вразнобой. «Думаю...» сюда не входит: она только открывающая. */
export const THINKING_PHRASES = [
  "Изучаю справочники...",
  "Подбираю варианты...",
  "Оцениваю маршрут...",
  "Считаю деньги...",
  "Размышляю над смыслом жизни...",
  "Пакую чемоданы...",
  "Создаю интригу...",
  "Бросаю монетку...",
  "Предвкушаю приключение...",
  "Сверяюсь с картой...",
  "Меняю доллары...",
  "Ищу, где заправиться...",
  "Оцениваю очереди на заправках...",
];

/**
 * Достаёт фразу из мешка. Пока мешок не опустеет, повторов нет — каждая
 * фраза показывается один раз за круг. Опустевший мешок набирается заново.
 *
 * На стыке кругов только что показанная фраза из выдачи исключается: она
 * остаётся в мешке и выпадет позже, но подряд дважды не покажется — это
 * выглядело бы как остановившийся таймер, а не как работа.
 *
 * @param bag  что осталось в мешке; пустой — набрать заново
 * @param prev фраза на экране сейчас
 * @param rnd  случайное число [0, 1) — параметром, чтобы поведение проверялось
 */
export function drawPhrase(
  bag: string[],
  prev?: string,
  rnd: number = Math.random(),
): { phrase: string; bag: string[] } {
  const pool = bag.length > 0 ? bag : THINKING_PHRASES;
  const pickable = pool.length > 1 ? pool.filter((p) => p !== prev) : pool;
  // rnd === 1 из Math.random() не приходит, но подстраховка дешевле, чем undefined
  const phrase = pickable[Math.min(pickable.length - 1, Math.floor(rnd * pickable.length))];
  return { phrase, bag: pool.filter((p) => p !== phrase) };
}
