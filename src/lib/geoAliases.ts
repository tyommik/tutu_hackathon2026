/** Город с аэропортом для острова/страны, если он очевиден. */
export function suggestDestination(name: string): string | undefined {
  const key = name.trim().toLowerCase().replace(/ё/g, "е");
  const hit = ALIASES[key];
  // подсказывать то же самое, что человек и написал, смысла нет
  return hit && hit.toLowerCase() !== key ? hit : undefined;
}

export interface ResolvedGeo {
  name?: string;
  iata?: string;
  region?: string;
}

/**
 * Строка «как Туту понял точку»: без неё пустая выдача выглядит как
 * поломка, хотя на деле поиск шёл в другой город.
 */
export function resolvedLabel(geo?: ResolvedGeo): string | undefined {
  if (!geo?.name) return undefined;
  const extra = [geo.iata, geo.region].filter(Boolean).join(", ");
  return extra ? `${geo.name} (${extra})` : geo.name;
}
